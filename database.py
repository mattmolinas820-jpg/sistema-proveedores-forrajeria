import os
import re
import sqlite3
from contextlib import contextmanager
from pathlib import Path


DB_PATH = Path(os.environ.get("DATABASE_PATH", Path(__file__).with_name("proveedores.db")))
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = DATABASE_URL.replace("postgres://", "postgresql://", 1)

try:
    from psycopg import IntegrityError as PostgresIntegrityError
except ImportError:
    PostgresIntegrityError = None

INTEGRITY_ERRORS = (sqlite3.IntegrityError,) + (
    (PostgresIntegrityError,) if PostgresIntegrityError else ()
)


class PostgresConnection:
    def __init__(self, connection):
        self._connection = connection

    @staticmethod
    def _query(sql):
        return re.sub(r"\?", "%s", sql)

    def execute(self, sql, parameters=()):
        return self._connection.execute(self._query(sql), parameters)

    def executemany(self, sql, parameters):
        return self._connection.executemany(self._query(sql), parameters)

    def begin_write(self, proveedor_id):
        self.execute("SELECT id FROM proveedores WHERE id = ? FOR UPDATE", (proveedor_id,))


@contextmanager
def get_db():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        connection = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        try:
            yield PostgresConnection(connection)
            connection.commit()
        except Exception:
            connection.rollback()
            raise
        finally:
            connection.close()
        return

    connection = sqlite3.connect(DB_PATH, timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    try:
        with connection:
            yield connection
    finally:
        connection.close()


def _init_postgres():
    with get_db() as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS proveedores (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                razon_social VARCHAR(150) NOT NULL,
                cuit_cuil VARCHAR(13) NOT NULL UNIQUE,
                email VARCHAR(100) NOT NULL DEFAULT '',
                telefono VARCHAR(50) NOT NULL DEFAULT '',
                estado SMALLINT NOT NULL DEFAULT 1 CHECK (estado IN (0, 1)),
                created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
            )
            """
        )
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS movimientos_ctacte (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                proveedor_id BIGINT NOT NULL REFERENCES proveedores (id) ON DELETE RESTRICT,
                fecha TEXT NOT NULL,
                tipo_comprobante TEXT NOT NULL CHECK (
                    tipo_comprobante IN (
                        'FACTURA_A', 'FACTURA_B', 'FACTURA_C', 'NOTA_DEBITO',
                        'ORDEN_PAGO', 'RECIBO', 'NOTA_CREDITO'
                    )
                ),
                numero_comprobante VARCHAR(50) NOT NULL,
                debe_centavos BIGINT NOT NULL DEFAULT 0 CHECK (debe_centavos >= 0),
                haber_centavos BIGINT NOT NULL DEFAULT 0 CHECK (haber_centavos >= 0),
                saldo_resultante_centavos BIGINT NOT NULL DEFAULT 0,
                vencimiento TEXT,
                observaciones TEXT NOT NULL DEFAULT '',
                created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
                UNIQUE (proveedor_id, tipo_comprobante, numero_comprobante),
                CHECK (
                    (debe_centavos > 0 AND haber_centavos = 0)
                    OR (haber_centavos > 0 AND debe_centavos = 0)
                )
            )
            """
        )
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS imputaciones (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                pago_id BIGINT NOT NULL REFERENCES movimientos_ctacte (id) ON DELETE RESTRICT,
                factura_id BIGINT NOT NULL REFERENCES movimientos_ctacte (id) ON DELETE RESTRICT,
                importe_centavos BIGINT NOT NULL CHECK (importe_centavos > 0),
                created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
                UNIQUE (pago_id, factura_id),
                CHECK (pago_id != factura_id)
            )
            """
        )
        connection.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_movimientos_proveedor_fecha
            ON movimientos_ctacte (proveedor_id, fecha, id)
            """
        )
        connection.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_movimientos_vencimiento
            ON movimientos_ctacte (vencimiento)
            """
        )
        connection.execute(
            """
            CREATE OR REPLACE FUNCTION prevent_movement_mutation()
            RETURNS trigger AS $$
            BEGIN
                RAISE EXCEPTION 'Los movimientos contables son inmutables';
            END;
            $$ LANGUAGE plpgsql
            """
        )
        connection.execute("DROP TRIGGER IF EXISTS movimientos_no_delete ON movimientos_ctacte")
        connection.execute(
            """
            CREATE TRIGGER movimientos_no_delete
            BEFORE DELETE ON movimientos_ctacte
            FOR EACH ROW EXECUTE FUNCTION prevent_movement_mutation()
            """
        )
        connection.execute("DROP TRIGGER IF EXISTS movimientos_no_edit ON movimientos_ctacte")
        connection.execute(
            """
            CREATE TRIGGER movimientos_no_edit
            BEFORE UPDATE OF proveedor_id, fecha, tipo_comprobante, numero_comprobante,
                debe_centavos, haber_centavos, vencimiento, observaciones, created_at
            ON movimientos_ctacte
            FOR EACH ROW EXECUTE FUNCTION prevent_movement_mutation()
            """
        )
        connection.execute("DROP TRIGGER IF EXISTS imputaciones_no_edit ON imputaciones")
        connection.execute(
            """
            CREATE TRIGGER imputaciones_no_edit
            BEFORE UPDATE OR DELETE ON imputaciones
            FOR EACH ROW EXECUTE FUNCTION prevent_movement_mutation()
            """
        )


def init_db():
    if DATABASE_URL:
        _init_postgres()
        return

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    with get_db() as connection:
        connection.executescript(
            """
            CREATE TABLE IF NOT EXISTS proveedores (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                razon_social TEXT NOT NULL,
                cuit_cuil TEXT NOT NULL UNIQUE,
                email TEXT NOT NULL DEFAULT '',
                telefono TEXT NOT NULL DEFAULT '',
                estado INTEGER NOT NULL DEFAULT 1 CHECK (estado IN (0, 1)),
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE TABLE IF NOT EXISTS movimientos_ctacte (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                proveedor_id INTEGER NOT NULL,
                fecha TEXT NOT NULL,
                tipo_comprobante TEXT NOT NULL CHECK (
                    tipo_comprobante IN (
                        'FACTURA_A', 'FACTURA_B', 'FACTURA_C', 'NOTA_DEBITO',
                        'ORDEN_PAGO', 'RECIBO', 'NOTA_CREDITO'
                    )
                ),
                numero_comprobante TEXT NOT NULL,
                debe_centavos INTEGER NOT NULL DEFAULT 0 CHECK (debe_centavos >= 0),
                haber_centavos INTEGER NOT NULL DEFAULT 0 CHECK (haber_centavos >= 0),
                saldo_resultante_centavos INTEGER NOT NULL DEFAULT 0,
                vencimiento TEXT,
                observaciones TEXT NOT NULL DEFAULT '',
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (proveedor_id) REFERENCES proveedores (id) ON DELETE RESTRICT,
                UNIQUE (proveedor_id, tipo_comprobante, numero_comprobante),
                CHECK (
                    (debe_centavos > 0 AND haber_centavos = 0)
                    OR (haber_centavos > 0 AND debe_centavos = 0)
                )
            );
            CREATE TABLE IF NOT EXISTS imputaciones (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                pago_id INTEGER NOT NULL,
                factura_id INTEGER NOT NULL,
                importe_centavos INTEGER NOT NULL CHECK (importe_centavos > 0),
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (pago_id) REFERENCES movimientos_ctacte (id) ON DELETE RESTRICT,
                FOREIGN KEY (factura_id) REFERENCES movimientos_ctacte (id) ON DELETE RESTRICT,
                UNIQUE (pago_id, factura_id),
                CHECK (pago_id != factura_id)
            );
            """
        )

        movement_columns = {
            row["name"] for row in connection.execute("PRAGMA table_info(movimientos_ctacte)")
        }
        if "debe_centavos" not in movement_columns:
            connection.execute(
                "ALTER TABLE movimientos_ctacte ADD COLUMN debe_centavos INTEGER NOT NULL DEFAULT 0"
            )
            connection.execute(
                "ALTER TABLE movimientos_ctacte ADD COLUMN haber_centavos INTEGER NOT NULL DEFAULT 0"
            )
            connection.execute(
                "ALTER TABLE movimientos_ctacte ADD COLUMN saldo_resultante_centavos INTEGER NOT NULL DEFAULT 0"
            )
            connection.execute("ALTER TABLE movimientos_ctacte ADD COLUMN vencimiento TEXT")
            connection.execute(
                "ALTER TABLE movimientos_ctacte ADD COLUMN created_at TEXT NOT NULL DEFAULT ''"
            )
            connection.execute(
                """
                UPDATE movimientos_ctacte
                SET debe_centavos = CAST(ROUND(COALESCE(debe, 0) * 100) AS INTEGER),
                    haber_centavos = CAST(ROUND(COALESCE(haber, 0) * 100) AS INTEGER),
                    saldo_resultante_centavos =
                        CAST(ROUND(COALESCE(saldo_resultante, 0) * 100) AS INTEGER)
                """
            )

        connection.executescript(
            """
            CREATE INDEX IF NOT EXISTS idx_movimientos_proveedor_fecha
                ON movimientos_ctacte (proveedor_id, fecha, id);
            CREATE INDEX IF NOT EXISTS idx_movimientos_vencimiento
                ON movimientos_ctacte (vencimiento);
            CREATE TRIGGER IF NOT EXISTS movimientos_no_delete
            BEFORE DELETE ON movimientos_ctacte
            BEGIN
                SELECT RAISE(ABORT, 'Los movimientos contables son inmutables');
            END;
            CREATE TRIGGER IF NOT EXISTS movimientos_no_edit
            BEFORE UPDATE OF proveedor_id, fecha, tipo_comprobante, numero_comprobante,
                debe_centavos, haber_centavos, vencimiento, observaciones, created_at
            ON movimientos_ctacte
            BEGIN
                SELECT RAISE(ABORT, 'Los movimientos contables son inmutables');
            END;
            CREATE TRIGGER IF NOT EXISTS imputaciones_no_edit
            BEFORE UPDATE ON imputaciones
            BEGIN
                SELECT RAISE(ABORT, 'Las imputaciones contables son inmutables');
            END;
            CREATE TRIGGER IF NOT EXISTS imputaciones_no_delete
            BEFORE DELETE ON imputaciones
            BEGIN
                SELECT RAISE(ABORT, 'Las imputaciones contables son inmutables');
            END;
            """
        )

        for proveedor in connection.execute("SELECT id FROM proveedores").fetchall():
            movements = connection.execute(
                """
                SELECT id, debe_centavos, haber_centavos
                FROM movimientos_ctacte WHERE proveedor_id = ? ORDER BY fecha, id
                """,
                (proveedor["id"],),
            ).fetchall()
            balance = 0
            for movement in movements:
                balance += movement["debe_centavos"] - movement["haber_centavos"]
                connection.execute(
                    "UPDATE movimientos_ctacte SET saldo_resultante_centavos = ? WHERE id = ?",
                    (balance, movement["id"]),
                )


if __name__ == "__main__":
    init_db()
    print(f"Base de datos inicializada en {DATABASE_URL or DB_PATH}")
